"""O1: transcribe the spec into data, written to docs/spec/.

Section 5.1-5.5 portfolio targets, section 6.2 scenario paths with units and SYNTHETIC status,
section 8.7 calibration targets, and every acceptance case as an oracle record: input, expected
value, tolerance and the named wrong answer. Rerun only when the requirements change version
(GOV-03): ``uv run python -m foundation.transcribe``; ``--check`` compares without writing.
"""

from pathlib import Path

import yaml

from foundation.transcribe.markdown import REQUIREMENTS_FILE, Spec
from foundation.transcribe.oracles import oracles
from foundation.transcribe.scenarios import calibration_targets, scenario_paths
from foundation.transcribe.targets import portfolio_targets, tolerances

HEADER = (
    "# Generated by foundation/transcribe (O1) from {doc} version {version}.\n"
    "# Locked: never edit by hand. Rerun O1 when the requirements change (GOV-03).\n"
)


def build(spec_dir: Path) -> dict[str, str]:
    """All O1 files as {relative path: text}."""
    spec = Spec(spec_dir / REQUIREMENTS_FILE)
    targets = portfolio_targets(spec)
    targets["tolerances"] = tolerances(spec)
    files = {
        "targets.yaml": targets,
        "scenarios.yaml": scenario_paths(spec, list(targets["countries"])),
        "calibration_targets.yaml": calibration_targets(spec),
    }
    for at_id, record in oracles(spec, targets["tolerances"]).items():
        files[f"oracles/{at_id}.yaml"] = record
    header = HEADER.format(doc=spec.path.name, version=spec.version)
    return {
        name: header + yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=100)
        for name, data in files.items()
    }


def write(spec_dir: Path) -> list[Path]:
    written = []
    for name, text in build(spec_dir).items():
        path = spec_dir / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
        written.append(path)
    return written


def check(spec_dir: Path) -> list[str]:
    """Names of O1 files that are missing or differ from what O1 would write now."""
    stale = []
    for name, text in build(spec_dir).items():
        path = spec_dir / name
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            stale.append(name)
    return stale
