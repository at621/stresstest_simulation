# --- requirement IDs -----------------------------------------------------------------------------

def find_ids(text: str, known: Iterable[str]) -> set[str]:
    """Every requirement in ``known`` that ``text`` names. Ranges expand with whichever dash
    appears and keep only known IDs, because the numbering has gaps (requirements section 1.3)."""
    known = set(known)
    families = "|".join(sorted({k.rsplit("-", 1)[0] for k in known}, key=len, reverse=True))
    if not families:
        return set()
    start = rf"(?<![A-Za-z0-9-])({families})-(\d{{2}})"
    found: set[str] = set()

    def expand(match: re.Match) -> str:
        family, low, high = match.group(1), int(match.group(2)), int(match.group(3))
        found.update(f"{family}-{n:02d}" for n in range(low, high + 1) or (low, high))
        return " "

    def listed(match: re.Match) -> str:
        found.update(f"{match.group(1)}-{n}" for n in [match.group(2), *match.group(3).split("/")[1:]])
        return " "

    # A bare second number needs a tight dash, so "ECL-08 - 12 months" stays one ID.
    dash = rf"(?:[{DASHES}](?:\1-)?|\s+[{DASHES}]\s+\1-)"
    rest = re.sub(rf"{start}{dash}(\d{{2}})(?![\dA-Za-z])", expand, text)
    rest = re.sub(rf"{start}((?:/\d{{2}})+)(?!\d)", listed, rest)
    found.update(f"{m.group(1)}-{m.group(2)}" for m in re.finditer(rf"{start}(?!\d)", rest))
    return found & known


@dataclass(frozen=True)
class Requirement:
    id: str
    section: str
    title: str


def walk(text: str) -> Iterator[tuple[str, str | None, str]]:
    """Each line with the requirement that owns it and its section number.

    A bold requirement owns its following lines up to the next requirement or heading, so a table
    or paragraph that continues it stays with it. A table-row requirement owns its row only."""
    owner, section = None, ""
    for line in text.splitlines():
        heading = HEADING.match(line)
        if line.startswith("#"):
            owner, section = None, f"§{heading.group(1)}" if heading else ""
            yield line, None, section
            continue
        definition = DEFINITION.match(line)
        if definition and line.startswith("|"):
            yield line, definition.group(1), section
            continue
        if definition:
            owner = definition.group(1)
        yield line, owner, section


def _title(line: str) -> str:
    """One line for the matrix: the requirement's own title, else its first sentence."""
    if line.startswith("|"):
        text = line.split("|")[2].strip()
    else:
        head, body = re.match(r"\*\*(.+?)\*\*\s*(.*)", line).groups()
        parts = [p.strip() for p in re.split(r"\s+—\s+", head.rstrip("."))]
        named = [p for p in parts[1:] if not re.fullmatch(r"[A-Z/]+", p)]
        text = named[-1] if named else body
        text = text[0].upper() + text[1:]
    text = re.split(r"(?<=[.;:])\s", text.replace("`", "").replace("**", ""), maxsplit=1)[0]
    text = text.rstrip(".;:")
    if len(text) > TITLE_LENGTH:
        text = text[:TITLE_LENGTH].rsplit(" ", 1)[0] + "…"
    return text


def parse_requirements(text: str) -> dict[str, Requirement]:
    """All requirements, in document order."""
    out: dict[str, Requirement] = {}
    for line, _, section in walk(text):
        definition = DEFINITION.match(line)
        if not definition:
            continue
        if definition.group(1) in out:
            raise TraceabilityError(f"{definition.group(1)} is defined twice in the requirements")
        out[definition.group(1)] = Requirement(definition.group(1), section, _title(line))
    if not out:
        raise TraceabilityError("no requirement IDs found in the requirements file")
    return out


def control_rows(text: str) -> dict[str, str]:
    """The section 12.2 controls as {name: required result}."""
    part = text.split("### 12.2", 1)[1].split("### 12.3", 1)[0]
    rows = (line.split("|") for line in part.splitlines() if line.startswith("| "))
    return {row[1].strip(): row[2].strip() for row in rows if row[1].strip() != "Control"}


# --- tests ---------------------------------------------------------------------------------------

@dataclass(frozen=True)
class MarkedTest:
    node: str  # path under tests/ and the test name
    ats: tuple[str, ...]
    reqs: tuple[str, ...]
    controls: tuple[str, ...]
    docstrings: str = ""  # module and test docstrings, read for acceptance cases only


def _marks(nodes: Iterable[ast.AST], where: str) -> dict[str, list[str]]:
    """The arguments of every ``pytest.mark.at/req/control`` call under ``nodes``."""
    marks: dict[str, list[str]] = {"at": [], "req": [], "control": []}
    for root in nodes:
        for node in ast.walk(root):
            if not (isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute)
                    and node.func.attr in marks and isinstance(node.func.value, ast.Attribute)
                    and node.func.value.attr == "mark"):
                continue
            for argument in node.args:
                if not (isinstance(argument, ast.Constant) and isinstance(argument.value, str)):
                    raise TraceabilityError(f"{where}: a {node.func.attr} marker needs a text literal")
                marks[node.func.attr].append(argument.value)
    return marks


def _module_marks(tree: ast.AST) -> list[ast.AST]:
    return [n for n in getattr(tree, "body", []) if isinstance(n, ast.Assign)
            and any(getattr(t, "id", "") == "pytestmark" for t in n.targets)]


def marked_tests(path: Path, name: str) -> list[MarkedTest]:
    """Every test in one file, with the markers of its module, class and function."""
    tree = ast.parse(path.read_text(encoding="utf-8"))
    module_doc = ast.get_docstring(tree) or ""
    module_marks = _module_marks(tree)
    found = []

    def add(node: ast.AST, label: str, outer: list[ast.AST]) -> None:
        marks = _marks([*outer, *node.decorator_list], f"{name}::{label}")
        found.append(MarkedTest(f"{name}::{label}", tuple(marks["at"]), tuple(marks["req"]),
                                tuple(marks["control"]),
                                f"{module_doc}\n{ast.get_docstring(node) or ''}"))

    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.name.startswith("test"):
            add(node, node.name, module_marks)
        elif isinstance(node, ast.ClassDef) and node.name.startswith("Test"):
            outer = [*module_marks, *node.decorator_list, *_module_marks(node)]
            for member in node.body:
                if isinstance(member, (ast.FunctionDef, ast.AsyncFunctionDef)) \
                        and member.name.startswith("test"):
                    add(member, f"{node.name}::{member.name}", outer)
    return found


def scan_tests(root: Path) -> list[MarkedTest]:
    tests_dir = root / "tests"
    paths = sorted(tests_dir.rglob("test_*.py"), key=lambda p: p.as_posix())
    found = []
    for path in paths:
        found.extend(marked_tests(path, path.relative_to(tests_dir).as_posix()))
    return found


# --- code, oracles, assumptions ------------------------------------------------------------------

def scan_code(root: Path, known: set[str]) -> dict[str, set[str]]:
    """{requirement ID: code files that name it}. Only Python and YAML count: the CLAUDE.md rule
    files in the code folders are instructions, not code."""
    named: dict[str, set[str]] = defaultdict(set)
    for folder in CODE_FOLDERS:
        for path in (root / folder).rglob("*"):
            relative = path.relative_to(root)
            if path.suffix not in CODE_SUFFIXES or not path.is_file() \
                    or any(p.startswith((".", "__pycache__")) for p in relative.parts):
                continue
            for requirement in find_ids(path.read_text(encoding="utf-8"), known):
                named[requirement].add(relative.as_posix())
    return named


def oracle_links(root: Path, known: set[str]) -> dict[str, set[str]]:
    """{acceptance case: the requirement IDs its oracle references}, for every oracle."""
    links = {}
    for path in sorted((root / ORACLES).glob("AT-*.yaml"), key=lambda p: p.name):
        record = yaml.safe_load(path.read_text(encoding="utf-8"))
        links[path.stem] = {r for r in record.get("references") or [] if r in known}
    return links


def scan_assumptions(text: str, known: set[str]) -> dict[str, list[str]]:
    """{requirement ID: the A and C numbers whose table row mentions it}, in document order."""
    mentioned: dict[str, list[str]] = defaultdict(list)
    for line in text.splitlines():
        row = ASSUMPTION_ROW.match(line)
        if row:
            for requirement in find_ids(line, known):
                mentioned[requirement].append(row.group(1))
    return mentioned


# --- links ---------------------------------------------------------------------------------------

@dataclass
class Links:
    """What the scan found, keyed by requirement ID."""

    acceptance: dict[str, set[str]] = field(default_factory=lambda: defaultdict(set))
    tests: dict[str, set[str]] = field(default_factory=lambda: defaultdict(set))
    code: dict[str, set[str]] = field(default_factory=lambda: defaultdict(set))
    decisions: dict[str, list[str]] = field(default_factory=lambda: defaultdict(list))
    decision_numbers: set[str] = field(default_factory=set)  # every A and C number
    case_tests: dict[str, str] = field(default_factory=dict)  # acceptance case: its test
    all_tests: set[str] = field(default_factory=set)


def collect_links(root: Path, text: str, known: set[str]) -> Links:
    links = Links()
    oracles = oracle_links(root, known)
    cases: dict[str, set[str]] = {case: set(refs) for case, refs in oracles.items()}
    controls = {name: find_ids(result, known) for name, result in control_rows(text).items()}
    for test in scan_tests(root):
        links.all_tests.add(test.node)
        for requirement in test.reqs:
            links.tests[requirement].add(test.node)
        for name in test.controls:
            for requirement in controls.get(name, ()):
                links.tests[requirement].add(test.node)
        for case in test.ats:
            links.case_tests[case] = test.node
            cases.setdefault(case, set()).update(find_ids(test.docstrings, known))
    for line, owner, _ in walk(text):
        if owner:
            for case in AT_ID.findall(line):
                if case in cases:
                    cases[case].add(owner)
    for case, requirements in cases.items():
        if case not in links.case_tests:
            continue  # an oracle with no test proves nothing, so it gives no link
        for requirement in requirements:
            links.acceptance[requirement].add(case)
    links.code = scan_code(root, known)
    assumptions = (root / ASSUMPTIONS).read_text(encoding="utf-8")
    links.decisions = scan_assumptions(assumptions, known)
    links.decision_numbers = set(ASSUMPTION_ROW.findall(assumptions))
    return links


# --- hand-kept status ----------------------------------------------------------------------------

@dataclass(frozen=True)
class Entry:
    """One entry of requirement-status.yaml. ``status`` is empty for a qualification."""

    status: str = ""
    reason: str = ""
    note: str = ""
    decided_in: tuple[str, ...] = ()
    evidence: tuple[str, ...] = ()
    acceptance: tuple[str, ...] = ()
    tests: tuple[str, ...] = ()
    code: tuple[str, ...] = ()


def _text_list(value) -> tuple[str, ...]:
    return tuple(str(v) for v in (value or []))


def load_status(root: Path, known: set[str], links: Links) -> dict[str, Entry]:
    """Read and check the YAML. Every problem is listed at once."""
    path = root / STATUS_FILE
    if not path.exists():
        raise TraceabilityError(f"{STATUS_FILE.as_posix()} is missing")
    raw = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    allowed = {"status", "reason", "note", "decided_in", "evidence", "acceptance", "tests", "code"}
    entries, problems = {}, []
    for requirement, fields in (raw.get("requirements") or {}).items():
        fields = fields or {}
        where = f"{STATUS_FILE.name}: {requirement}"
        if requirement not in known:
            problems.append(f"{where} is not a requirement ID")
            continue
        unknown = sorted(set(fields) - allowed)
        if unknown:
            problems.append(f"{where} has unknown fields {unknown}")
            continue
        code = []
        for item in fields.get("code") or []:
            target = root / item["path"]
            if not target.is_file() or item["contains"] not in target.read_text(encoding="utf-8"):
                problems.append(f"{where}: {item['path']} does not contain {item['contains']!r}")
            code.append(item["path"])
        entry = Entry(str(fields.get("status") or ""), str(fields.get("reason") or ""),
                      str(fields.get("note") or ""), _text_list(fields.get("decided_in")),
                      _text_list(fields.get("evidence")), _text_list(fields.get("acceptance")),
                      _text_list(fields.get("tests")), tuple(code))
        if entry.status and entry.status not in HAND_STATUSES:
            problems.append(f"{where}: status {entry.status!r} is not allowed here: "
                            f"tested and built are derived, the YAML holds {HAND_STATUSES}")
        if not entry.reason:
            problems.append(f"{where} has no reason")
        if entry.status == "deferred" and entry.reason != UNMET and not entry.decided_in:
            problems.append(f"{where} is deferred with no decision: name where it was decided, "
                            f"or give the reason {UNMET!r}")
        if entry.status == "process" and not entry.evidence:
            problems.append(f"{where} is process with no evidence")
        problems += [f"{where}: evidence {e} does not exist" for e in entry.evidence
                     if not (root / e).exists() and Path(e) not in (MATRIX, REGISTER)]
        problems += [f"{where}: {c} is not an acceptance case with a test" for c in entry.acceptance
                     if c not in links.case_tests]
        problems += [f"{where}: {t} is not a test" for t in entry.tests if t not in links.all_tests]
        problems += [f"{where}: {d} is not in {ASSUMPTIONS.name}" for d in entry.decided_in
                     if re.fullmatch(r"[AC]\d+", d) and d not in links.decision_numbers]
        entries[requirement] = entry
    if problems:
        raise TraceabilityError("\n".join(problems))
    return entries


# --- matrix --------------------------------------------------------------------------------------

@dataclass(frozen=True)
class Row:
    requirement: Requirement
    status: str
    acceptance: tuple[str, ...]
    tests: tuple[str, ...]
    code: tuple[str, ...]
    decisions: tuple[str, ...]
    reason: str


def _reason(entry: Entry) -> str:
    if not entry.reason:
        return ""
    parts = [entry.reason if entry.reason.endswith(".") else f"{entry.reason}."]
    if entry.note:
        parts.append(entry.note)
    if entry.evidence:
        parts.append("Evidence: " + ", ".join(f"`{e}`" for e in entry.evidence) + ".")
    return " ".join(parts)


def classify(requirements: dict[str, Requirement], links: Links,
             entries: dict[str, Entry]) -> list[Row]:
    """One row per requirement with exactly one status, or an error naming every gap."""
    rows, missing = [], []
    for requirement in requirements.values():
        key = requirement.id
        entry = entries.get(key, Entry())
        acceptance = tuple(sorted(links.acceptance.get(key, set()) | set(entry.acceptance)))
        tests = tuple(sorted(links.tests.get(key, set()) | set(entry.tests)))
        code = tuple(sorted(links.code.get(key, set()) | set(entry.code)))
        derived = "tested" if acceptance or tests else "built" if code else ""
        status = entry.status or derived
        if not status:
            missing.append(key)
            continue
        decisions = tuple(dict.fromkeys([*links.decisions.get(key, []), *entry.decided_in]))
        rows.append(Row(requirement, status, acceptance, tests, code, decisions, _reason(entry)))
    if missing:
        raise TraceabilityError(
            f"{len(missing)} requirement(s) have no status: {', '.join(missing)}. There is no "
            f"'unknown' status: add a test marker, or an entry in {STATUS_FILE.as_posix()}.")
    return rows


def _cell(items: Iterable[str], code: bool = False) -> str:
    return ", ".join(f"`{i}`" if code else i for i in items)


def _escape(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def render_matrix(rows: list[Row], links: Links, version: str) -> str:
    counts = {status: sum(r.status == status for r in rows) for status in STATUSES}
    unmet = [r.requirement.id for r in rows if r.reason.startswith(UNMET)]
    linked = {case for row in rows for case in row.acceptance}
    unlinked = sorted(set(links.case_tests) - linked)
    head = MATRIX_HEAD.format(
        status_file=STATUS_FILE.as_posix(), version=version, total=len(rows), **counts,
        unmet_count=len(unmet), unmet=UNMET, unmet_list=f": {', '.join(unmet)}." if unmet else ".",
        unlinked=f"Acceptance cases linked to no requirement: {', '.join(unlinked)}.\n\n"
        if unlinked else "")
    body = [
        "| " + " | ".join([
            r.requirement.id, _escape(r.requirement.title), f"`{r.status}`", _cell(r.acceptance),
            _cell(r.tests, code=True), _cell(r.code, code=True), _escape(_cell(r.decisions)),
            _escape(r.reason)]) + " |"
        for r in rows
    ]
    return head + "\n".join(body) + "\n"


