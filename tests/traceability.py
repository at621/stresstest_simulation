@dataclass(frozen=True)
class Source:
    id: str
    title: str
    version: str
    published: str
    url: str


def parse_sources(text: str) -> dict[str, Source]:
    """The section 15 list, with version and date taken only from the requirements file."""
    part = text.split("## 15. Sources", 1)[1]
    basis = re.search(r"\*\*Regulatory basis:\*\*.*?published on (\d{1,2} \w+ \d{4})", text)
    checked = re.search(r"Sources were checked on (\d{1,2} \w+ \d{4})", part)
    draft = re.search(r"refer to the (\w+ \d{4} draft)", part)
    sources = {}
    for line in part.splitlines():
        entry = SOURCE_ENTRY.match(line)
        if not entry:
            continue
        source, title, rest = entry.groups()
        title = title.rstrip(".").rstrip("”").rstrip(".").replace("“", "\"")
        title = title + "\"" if title.count("\"") % 2 else title
        url = re.search(r"\]\((https?://[^)]+)\)", rest)
        dated = re.search(r"\b(\d{1,2} \w+ \d{4})\b", title)
        is_draft = "Draft" in title
        published = (dated.group(1) if dated else basis.group(1) if is_draft and basis
                     else f"{NOT_RECORDED}; page checked {checked.group(1)}" if checked
                     else NOT_RECORDED)
        version = draft.group(1).capitalize() if is_draft and draft else NOT_RECORDED
        sources[source] = Source(source, title, version, published, url.group(1) if url else "")
    if not sources:
        raise TraceabilityError("no sources found in section 15 of the requirements")
    return sources


def expand_anchor(anchor: str) -> list[str]:
    """One anchor per row: ``¶123–125`` gives three, ``Boxes 4–9`` six, and a bare number after
    ``§§a, b`` is a section."""
    anchor = re.sub(r"\s+", " ", re.sub(rf"[{DASHES}]", "–", anchor.strip()))
    if anchor.startswith(("Annex", "footnote")):
        return [anchor]
    if anchor.startswith("Box"):
        low, _, high = anchor.split(" ", 1)[1].partition("–")
        return [f"Box {n}" for n in range(int(low), int(high or low) + 1)]
    if anchor.startswith("¶"):
        low, _, high = anchor.lstrip("¶ ").partition("–")
        return [f"¶{n}" for n in range(int(low), int(high or low) + 1)]
    low, _, high = anchor.lstrip("§ ").partition("–")
    if not high:
        return [f"§{low}"]
    stem, first = low.rsplit(".", 1) if "." in low else ("", low)
    last = high.rsplit(".", 1)[-1]
    return [f"§{stem + '.' if stem else ''}{n}" for n in range(int(first), int(last) + 1)]


def _anchor_key(anchor: str) -> tuple:
    kind = next((i for i, k in enumerate(("¶", "Box", "§", "Annex", "footnote")) if
                 anchor.startswith(k)), 5)
    return kind, [int(n) for n in re.findall(r"\d+", anchor)], anchor


def parse_citations(text: str, sources: dict[str, Source]) -> dict[tuple[str, str], set[str]]:
    """{(source, anchor): what cites it}: requirement IDs, or the section where no ID owns the line.

    S3 is also the name of Stage 3, so a citation needs a paragraph, section, box or annex after
    it; a section sign alone is a reference inside the requirements, not to a source."""
    cited: dict[tuple[str, str], set[str]] = defaultdict(set)
    body, _, closing = text.partition("## 15. Sources")
    for line, owner, section in walk(body):
        who = owner or section
        for first, last in WHOLE_SOURCES.findall(line):
            for number in range(int(first), int(last) + 1):
                cited[f"S{number}", WHOLE_DOCUMENT].add(who)
        for source, run in CITATION.findall(line):
            for anchor in ANCHOR_PART.findall(run):
                for part in expand_anchor(anchor):
                    cited[source, part].add(who)
        for anchor in BARE_PARAGRAPH.findall(CITATION.sub(" ", line)):
            for part in expand_anchor(anchor):
                cited[PRIMARY_SOURCE, part].add(who)
    for line in closing.splitlines():
        entry = SOURCE_ENTRY.match(line)
        scope = re.search(r"particularly (.+?) for the retained scope", line)
        if entry and scope:
            for anchor in ANCHOR_PART.findall(scope.group(1)):
                for part in expand_anchor(anchor):
                    cited[entry.group(1), part].add("§15")
    unknown = sorted({source for source, _ in cited} - set(sources))
    if unknown:
        raise TraceabilityError(f"citations name sources missing from section 15: {unknown}")
    for source in sources:
        if not any(s == source for s, _ in cited):
            cited[source, WHOLE_DOCUMENT].add("§15")
    return cited


def load_approvals(root: Path, cited: dict[tuple[str, str], set[str]]) -> dict[str, str]:
    """{"S3" or "S3 ¶123": ISO date}. A date applies only if the repository records it."""
    path = root / APPROVALS_FILE
    raw = yaml.safe_load(path.read_text(encoding="utf-8")) if path.exists() else None
    approvals = {str(k): str(v) for k, v in ((raw or {}).get("approvals") or {}).items()}
    rows = {f"{source} {anchor}" for source, anchor in cited} | {s for s, _ in cited}
    for key, value in approvals.items():
        if key not in rows or not re.fullmatch(r"\d{4}-\d{2}-\d{2}", value):
            raise TraceabilityError(f"{APPROVALS_FILE.name}: {key}: {value} is not a dated "
                                    "approval of a source or a register row")
    return approvals


def _owner_key(requirements: list[str]):
    order = {r: i for i, r in enumerate(requirements)}
    return lambda who: (who not in order, order.get(who, 0), who)


def render_register(sources: dict[str, Source], cited: dict[tuple[str, str], set[str]],
                    approvals: dict[str, str], requirements: list[str], version: str) -> str:
    head = REGISTER_HEAD.format(
        approvals_file=APPROVALS_FILE.as_posix(), version=version, not_approved=NOT_APPROVED,
        no_approval="" if approvals else NO_APPROVAL)
    order = _owner_key(requirements)
    rows = []
    for (source, anchor), who in sorted(cited.items(),
                                        key=lambda kv: (kv[0][0], _anchor_key(kv[0][1]))):
        info = sources[source]
        approved = approvals.get(f"{source} {anchor}", approvals.get(source, NOT_APPROVED))
        link = f"[link]({info.url})" if info.url else NOT_RECORDED
        rows.append("| " + " | ".join([
            _escape(f"{source}: {info.title}"), info.version, info.published, link, anchor,
            approved, ", ".join(sorted(who, key=order))]) + " |")
    return head + "\n".join(rows) + "\n"


# --- build, write, check -------------------------------------------------------------------------

def _rows(root: Path, text: str) -> tuple[dict[str, Requirement], Links, list[Row]]:
    requirements = parse_requirements(text)
    known = set(requirements)
    links = collect_links(root, text, known)
    return requirements, links, classify(requirements, links, load_status(root, known, links))


def build(root: Path = ROOT) -> dict[Path, str]:
    """Both generated files as {path under the root: text}."""
    text = (root / REQUIREMENTS.relative_to(ROOT)).read_text(encoding="utf-8")
    version = re.search(r"\*\*Document version:\*\* ([\d.]+)", text).group(1)
    requirements, links, rows = _rows(root, text)
    sources = parse_sources(text)
    cited = parse_citations(text, sources)
    return {
        MATRIX: render_matrix(rows, links, version),
        REGISTER: render_register(sources, cited, load_approvals(root, cited), list(requirements),
                                  version),
    }


def needs_review(root: Path = ROOT) -> list[str]:
    """Requirements the YAML calls unmet that a test now names. Not an error: a new marker on
    another branch must not stop the build, but a person should look at the entry again."""
    _, _, rows = _rows(root, (root / REQUIREMENTS.relative_to(ROOT)).read_text(encoding="utf-8"))
    return [r.requirement.id for r in rows if r.reason.startswith(UNMET) and (r.acceptance or r.tests)]


def write(root: Path = ROOT) -> list[Path]:
    written = []
    for name, text in build(root).items():
        path = root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
        written.append(name)
    return written


def check(root: Path = ROOT) -> list[str]:
    """Names of generated files that are missing or differ from what the generator would write."""
    return [name.as_posix() for name, text in build(root).items()
            if not (root / name).exists() or (root / name).read_text(encoding="utf-8") != text]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m tests.traceability", description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="compare with the files; write nothing")
    args = parser.parse_args(argv)
    try:
        if args.check:
            stale = check()
            for name in stale:
                print(f"stale: {name}")
            print("traceability files are current" if not stale else f"{len(stale)} file(s) differ")
            return 1 if stale else 0
        for name in write():
            print(f"wrote {name.as_posix()}")
        for requirement in needs_review():
            print(f"review: {requirement} is unmet in {STATUS_FILE.name} but a test now names it")
    except TraceabilityError as error:
        print(error, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
