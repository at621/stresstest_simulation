"""Blocking errors and rejection reason codes shared by all steps.

A blocking error stops the run: R11 seals the folder with status BLOCKED and the reason.
A rejection removes one record from processing; it goes to rejections.parquet with a reason
code and never reaches a total (section 12.2).
"""

from enum import StrEnum


class BlockingError(Exception):
    """A condition that stops the run or the calculation that needs the value."""

    def __init__(self, step: str, code: str, message: str):
        super().__init__(f"[{step}] {code}: {message}")
        self.step = step
        self.code = code
        self.message = message


